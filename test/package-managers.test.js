import test from 'node:test'
import assert from 'node:assert/strict'
import { readFile, mkdtemp, rm, writeFile } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import spawn from 'cross-spawn'

import { findCommand } from '../lib/aliases.js'
import { runCommand } from '../lib/commands.js'
import {
  PACKAGE_MANAGERS,
  detectPackageManager,
  installHint,
} from '../lib/package-managers.js'

async function withProject(files, callback) {
  const directory = await mkdtemp(path.join(os.tmpdir(), 'dev-workspace-pm-'))

  try {
    for (const [name, content] of Object.entries(files)) {
      await writeFile(path.join(directory, name), content, 'utf8')
    }

    await callback(directory)
  } finally {
    await rm(directory, { recursive: true, force: true })
  }
}

const packageJson = fields => JSON.stringify({ name: 'example', ...fields })

test('detectPackageManager prefers the packageManager field', async () => {
  await withProject(
    {
      'package.json': packageJson({ packageManager: 'pnpm@9.1.0+sha512.abc' }),
      'yarn.lock': '',
    },
    async directory => {
      assert.deepEqual(await detectPackageManager(directory), {
        name: 'pnpm',
        source: 'packageManager',
        runsHooks: true,
      })
    },
  )
})

test('detectPackageManager reads a package.json that starts with a byte order mark', async () => {
  await withProject(
    {
      'package.json': '\uFEFF' + packageJson({ packageManager: 'pnpm@9.1.0' }),
      'yarn.lock': '',
    },
    async directory => {
      assert.deepEqual(await detectPackageManager(directory), {
        name: 'pnpm',
        source: 'packageManager',
        runsHooks: true,
      })
    },
  )
})

test('detectPackageManager falls back to the lockfile', async () => {
  const cases = [
    ['pnpm-lock.yaml', 'pnpm'],
    ['yarn.lock', 'yarn'],
    ['bun.lock', 'bun'],
    ['bun.lockb', 'bun'],
    ['package-lock.json', 'npm'],
    ['npm-shrinkwrap.json', 'npm'],
  ]

  for (const [lockfile, name] of cases) {
    await withProject(
      { 'package.json': packageJson({}), [lockfile]: '' },
      async directory => {
        assert.deepEqual(await detectPackageManager(directory), {
          name,
          source: lockfile,
          runsHooks: true,
        })
      },
    )
  }
})

test('detectPackageManager uses a fixed order for several lockfiles', async () => {
  await withProject(
    { 'package-lock.json': '', 'yarn.lock': '', 'pnpm-lock.yaml': '' },
    async directory => {
      assert.equal((await detectPackageManager(directory)).name, 'pnpm')
    },
  )
})

test('detectPackageManager ignores unknown or invalid packageManager values', async () => {
  const values = ['deno@2.0.0', 42, '', '@1.0.0']

  for (const value of values) {
    await withProject(
      {
        'package.json': packageJson({ packageManager: value }),
        'yarn.lock': '',
      },
      async directory => {
        assert.deepEqual(await detectPackageManager(directory), {
          name: 'yarn',
          source: 'yarn.lock',
          runsHooks: true,
        })
      },
    )
  }
})

test('detectPackageManager defaults to npm', async () => {
  await withProject({ 'package.json': '{ invalid json' }, async directory => {
    assert.deepEqual(await detectPackageManager(directory), {
      name: 'npm',
      source: 'default',
      runsHooks: true,
    })
  })

  await withProject({}, async directory => {
    assert.equal((await detectPackageManager(directory)).name, 'npm')
  })
})

test('installHint offers Corepack only where Node.js ships it', () => {
  for (const name of ['pnpm', 'yarn']) {
    assert.equal(
      installHint(name, '24.11.1'),
      `Install it with "corepack enable ${name}" or "npm install --global ${name}".`,
    )

    for (const nodeVersion of ['25.0.0', '26.12.1']) {
      assert.equal(
        installHint(name, nodeVersion),
        `Install it with "npm install --global ${name}", or with "npm install --global corepack" followed by "corepack enable ${name}".`,
      )
    }
  }

  assert.match(installHint('npm', '26.0.0'), /Install Node\.js with npm/)
  assert.match(installHint('bun', '20.0.0'), /https:\/\/bun\.sh/)
  assert.equal(installHint('toString'), 'Install it, then restart the CLI.')
})

const YARN_1_LOCKFILE = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


left-pad@^1.3.0:
  version "1.3.0"
`

const YARN_BERRY_LOCKFILE = `# This file is generated by running "yarn install" inside your project.
# Manual changes might be lost - proceed with caution!

__metadata:
  version: 8
  cacheKey: 10c0
`

test('detectPackageManager recognises Yarn 2+, which does not run hooks', async () => {
  const cases = [
    ['yarn@4.18.1', '', false],
    ['yarn@2.4.2', YARN_1_LOCKFILE, false],
    ['yarn@1.22.22', YARN_BERRY_LOCKFILE, true],
    ['yarn', YARN_BERRY_LOCKFILE, false],
    ['yarn', YARN_1_LOCKFILE, true],
    [undefined, YARN_BERRY_LOCKFILE, false],
    [undefined, YARN_1_LOCKFILE, true],
    [undefined, '', true],
  ]

  for (const [packageManager, lockfile, runsHooks] of cases) {
    await withProject(
      {
        'package.json': packageJson({ packageManager }),
        'yarn.lock': lockfile,
      },
      async directory => {
        const detected = await detectPackageManager(directory)

        assert.equal(detected.name, 'yarn')
        assert.equal(
          detected.runsHooks,
          runsHooks,
          `${packageManager} with ${lockfile ? lockfile.split('\n')[0] : 'an empty yarn.lock'}`,
        )
      },
    )
  }
})

test('detectPackageManager reports that other tools run hooks', async () => {
  await withProject(
    {
      'package.json': packageJson({ packageManager: 'pnpm@10.0.0' }),
      'yarn.lock': YARN_BERRY_LOCKFILE,
    },
    async directory => {
      assert.equal((await detectPackageManager(directory)).runsHooks, true)
    },
  )
})

// Run a real script with every package manager installed on this machine.
// The script records npm_config_user_agent, which each tool sets to its own
// name, proving which tool ran it. Its pre and post hooks leave marker files,
// proving the tool ran them. CI installs all of them and sets
// REQUIRE_ALL_PACKAGE_MANAGERS so none is skipped there.
//
// The variable is removed first: when the tests run under `npm test`, npm has
// already set it, and Bun keeps an existing value instead of replacing it.
// npm also puts this project's node_modules/.bin first on PATH, where the
// Yarn 4 devDependency would stand in for the installed `yarn`, so that entry
// is dropped too.
const localBin = fileURLToPath(new URL('../node_modules/.bin', import.meta.url))
const samePath = (a, b) =>
  process.platform === 'win32'
    ? path.resolve(a).toLowerCase() === path.resolve(b).toLowerCase()
    : path.resolve(a) === path.resolve(b)

const cleanEnv = Object.fromEntries(
  Object.entries(process.env)
    .filter(([key]) => key.toLowerCase() !== 'npm_config_user_agent')
    .map(([key, value]) =>
      key.toLowerCase() === 'path'
        ? [
            key,
            value
              .split(path.delimiter)
              .filter(entry => !entry || !samePath(entry, localBin))
              .join(path.delimiter),
          ]
        : [key, value],
    ),
)

for (const name of Object.keys(PACKAGE_MANAGERS)) {
  const installed = await findCommand(name)
  const required = process.env.REQUIRE_ALL_PACKAGE_MANAGERS === '1'

  test(
    `runCommand runs a real script with ${name}`,
    { skip: !installed && !required && `${name} is not installed` },
    async () => {
      await withProject(
        {
          'package.json': packageJson({
            scripts: {
              prerecord: 'node hook.js pre',
              record: 'node record.js',
              postrecord: 'node hook.js post',
            },
          }),
          'record.js':
            "require('fs').writeFileSync('agent.txt', String(process.env.npm_config_user_agent))\n",
          'hook.js':
            "require('fs').writeFileSync(process.argv[2] + '.txt', '')\n",
        },
        async directory => {
          const result = await runCommand('record', directory, {
            packageManager: name,
            // Keep the test output clean; the real CLI inherits stdio.
            spawnProcess: (command, args, options) =>
              spawn(command, args, {
                ...options,
                env: cleanEnv,
                stdio: 'ignore',
              }),
          })

          assert.deepEqual(result, { code: 0 })

          const agent = await readFile(
            path.join(directory, 'agent.txt'),
            'utf8',
          )

          assert.ok(agent.startsWith(`${name}/`), agent)

          // Without a packageManager field or a Yarn 2+ lockfile, every tool
          // here runs hooks, which is why getScripts() groups them.
          for (const hook of ['pre', 'post']) {
            await assert.doesNotReject(
              readFile(path.join(directory, `${hook}.txt`)),
              `${name} did not run the ${hook}record hook`,
            )
          }
        },
      )
    },
  )
}

// Yarn 2 and later never run pre/post hooks. The installed `yarn` (Yarn 1 in
// CI) hands over to the Yarn 4 devDependency named by yarnPath, which needs
// the project installed first; with no dependencies, that is offline. CI sets
// the CI variable, which makes Yarn 4 refuse to create the lockfile unless
// immutable installs are turned off.
const YARN_BERRY = fileURLToPath(
  import.meta.resolve('@yarnpkg/cli-dist/bin/yarn.js'),
)

const yarnBerryEnv = {
  ...cleanEnv,
  YARN_ENABLE_IMMUTABLE_INSTALLS: 'false',
  YARN_ENABLE_TELEMETRY: 'false',
}

test(
  'runCommand runs a real script with Yarn 2+, which skips its hooks',
  {
    skip:
      !(await findCommand('yarn')) &&
      process.env.REQUIRE_ALL_PACKAGE_MANAGERS !== '1' &&
      'yarn is not installed',
  },
  async () => {
    await withProject(
      {
        'package.json': packageJson({
          scripts: {
            prerecord: 'node hook.js pre',
            record: 'node record.js',
            postrecord: 'node hook.js post',
          },
        }),
        'record.js':
          "require('fs').writeFileSync('agent.txt', String(process.env.npm_config_user_agent))\n",
        'hook.js':
          "require('fs').writeFileSync(process.argv[2] + '.txt', '')\n",
        // A JSON string is also a valid YAML string, backslashes included.
        '.yarnrc.yml': `yarnPath: ${JSON.stringify(YARN_BERRY)}\n`,
        'yarn.lock': '',
      },
      async directory => {
        const install = spawn.sync('yarn', ['install'], {
          cwd: directory,
          env: yarnBerryEnv,
          encoding: 'utf8',
        })

        assert.equal(install.status, 0, install.stdout + install.stderr)

        const detected = await detectPackageManager(directory)

        assert.deepEqual(detected, {
          name: 'yarn',
          source: 'yarn.lock',
          runsHooks: false,
        })

        const result = await runCommand('record', directory, {
          packageManager: detected.name,
          spawnProcess: (command, args, options) =>
            spawn(command, args, {
              ...options,
              env: yarnBerryEnv,
              stdio: 'ignore',
            }),
        })

        assert.deepEqual(result, { code: 0 })

        const agent = await readFile(path.join(directory, 'agent.txt'), 'utf8')

        assert.ok(agent.startsWith('yarn/4.'), agent)

        for (const hook of ['pre', 'post']) {
          await assert.rejects(
            readFile(path.join(directory, `${hook}.txt`)),
            `Yarn 2+ ran the ${hook}record hook`,
          )
        }
      },
    )
  },
)
